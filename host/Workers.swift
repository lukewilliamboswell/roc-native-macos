// Workers (roc-signals design.md, "Workers" and "Prepared state";
// docs/architecture.adoc, "Workers").
//
// A task's job runs in a worker instance: the same compiled module the page
// runs, entered through the worker entry points (`roc_engine_work`,
// `roc_engine_prepare`, `roc_engine_ask`, `roc_engine_forget`) on a thread
// of its own. Each worker thread holds one instance at a time, and an
// instance is three things the thread alone touches:
//
// - its heap: every allocation Roc makes on that thread, linked into one
//   list (`WorkerContext`), so the whole heap can be freed at once;
// - its handle table: the files and builders its jobs hold (`HandleTable`);
// - the prepared state it keeps between jobs, an opaque box.
//
// Nothing Roc owns crosses a thread. A job crosses as bytes and `FileEntry`
// values (plain Swift data: a path and a size); its answer comes back as
// bytes and `FileEntry` values, and the main thread mints the page's
// handles for those files when it delivers the answer as result tag 10.
// Roc's reference counts are not atomic, and they never need to be: no Roc
// value is reachable from two threads.
//
// Containment: each call into a worker instance runs under a jump point
// (`roc_guarded_*`, generated by glue/SwiftGlue.roc). A crash, an
// allocation failure, a failed `expect`, a resource limit or a stop
// request in that call unwinds to the jump point (`roc_guard_unwind`) from
// the runtime symbol or hosted function that met it, and the host then
// frees the instance's whole heap and table and starts a fresh instance for
// the next job. The page's instance and every other worker are untouched.
// docs/architecture.adoc states why unwinding is safe.

import AppKit

// MARK: - Fault classes

/// Why a job has no answer (design.md, Appendix B, result tag 11).
enum WorkFault {
    case contract, resourceLimit, outOfMemory, appCrash, expectFailed, unavailable, executor

    /// The class's code on the wire.
    var rawValue: UInt8 {
        switch self {
        case .contract: return 1
        case .resourceLimit: return 2
        case .outOfMemory: return 3
        case .appCrash: return 4
        case .expectFailed: return 5
        case .unavailable: return 6
        case .executor: return 7
        }
    }

    /// The class a code names; anything else is the host's own failure.
    static func of(_ code: UInt8) -> WorkFault {
        switch code {
        case 1: return .contract
        case 2: return .resourceLimit
        case 3: return .outOfMemory
        case 4: return .appCrash
        case 5: return .expectFailed
        case 6: return .unavailable
        default: return .executor
        }
    }

    var name: String {
        switch self {
        case .contract: return "contract"
        case .resourceLimit: return "resource_limit"
        case .outOfMemory: return "out_of_memory"
        case .appCrash: return "app_crash"
        case .expectFailed: return "expect_failed"
        case .unavailable: return "unavailable"
        case .executor: return "executor"
        }
    }
}

// MARK: - The worker context: what the runtime symbols reach on a worker thread

/// The bytes before each allocation of a worker instance: the links of its
/// heap list (previous, next), the size Roc asked for and the distance from
/// the allocation's start to what Roc sees. Roc never sees them.
private let linkBytes = 32

/// The most diagnostic text a fault keeps.
private let messageCapacity = 512

/// One worker thread's state for the runtime symbols, in memory of its own
/// so they reach it with plain loads (no reference counting on the hot
/// path). Only its thread touches it, except `stop`, which the main thread
/// sets to ask a running job to stop.
struct WorkerContext {
    /// The current guarded call's jump point.
    var jump: UnsafeMutablePointer<jmp_buf>
    /// A guarded call is running: a fault may unwind it.
    var inCall = false
    /// The newest live allocation's link; the heap is a doubly linked list.
    var head: UnsafeMutableRawPointer? = nil
    var liveBytes = 0
    var liveCount = 0
    /// Set (non-zero) by the main thread when the job is stopped. Read on
    /// every allocation and hosted call; a stale read only delays the stop to
    /// the next one.
    var stop: UnsafeMutablePointer<UInt8>
    /// Why the last call unwound: 0 when it was stopped, else a `WorkFault`.
    var fault: UInt8 = 0
    var message: UnsafeMutablePointer<UInt8>
    var messageLength = 0
    /// The instance's handle table, as `roc_dealloc` checks an address.
    var tableStart: UnsafeMutableRawPointer
    var tableBytes = 0
    /// The `WorkerThread` running this instance, unretained: it outlives its
    /// thread's context.
    var worker: UnsafeMutableRawPointer

    var thread: WorkerThread { Unmanaged<WorkerThread>.fromOpaque(worker).takeUnretainedValue() }

    /// The worker context of the calling thread, or nil on the main thread
    /// (and any thread that runs no worker instance).
    static var current: UnsafeMutablePointer<WorkerContext>? {
        pthread_getspecific(workerKey)?.assumingMemoryBound(to: WorkerContext.self)
    }

    /// In a hosted function: the running job's context. Outside a job a
    /// hosted effect is the caller's contract error, as in roc-signals: on
    /// the page's instance it stops the app.
    static func job(_ effect: String) -> UnsafeMutablePointer<WorkerContext> {
        guard let context = current, context.pointee.inCall else {
            fatal("contract: \(effect) is a worker effect and ran outside a job; only a worker task's job (Worker.task) may call it")
        }
        context.checkStop()
        return context
    }
}

/// The thread-specific key of `WorkerContext.current`; only worker threads
/// set it.
let workerKey: pthread_key_t = {
    var key = pthread_key_t()
    if pthread_key_create(&key, nil) != 0 { fatal("cannot create the worker thread key") }
    return key
}()

extension UnsafeMutablePointer where Pointee == WorkerContext {
    /// `roc_alloc` on a worker thread: from the instance's heap.
    func allocate(_ size: Int, _ alignment: Int) -> UnsafeMutableRawPointer {
        checkStop()
        let header = alignment > linkBytes ? alignment : linkBytes
        var raw: UnsafeMutableRawPointer? = nil
        if posix_memalign(&raw, max(alignment, 16), header + max(size, 1)) != 0 || raw == nil {
            fault(.outOfMemory, "out_of_memory: a worker job could not allocate memory")
        }
        let payload = raw! + header
        let link = payload - linkBytes
        let next = pointee.head
        link.storeBytes(of: nil, toByteOffset: 0, as: UnsafeMutableRawPointer?.self)
        link.storeBytes(of: next, toByteOffset: 8, as: UnsafeMutableRawPointer?.self)
        link.storeBytes(of: size, toByteOffset: 16, as: Int.self)
        link.storeBytes(of: header, toByteOffset: 24, as: Int.self)
        next?.storeBytes(of: link, toByteOffset: 0, as: UnsafeMutableRawPointer?.self)
        pointee.head = link
        pointee.liveBytes += size
        pointee.liveCount += 1
        if poisonAllocations { memset(payload, 0x5A, max(size, 1)) }
        return payload
    }

    /// `roc_dealloc` on a worker thread: a handle retires its slot in the
    /// instance's table; anything else leaves the heap.
    func deallocate(_ ptr: UnsafeMutableRawPointer) {
        let offset = ptr - pointee.tableStart
        if offset >= 0, offset < pointee.tableBytes {
            if pointee.thread.table.route(ptr) { return }
        }
        if fileHandles.contains(ptr) { fatal("a page file handle reached a worker instance") }
        let link = ptr - linkBytes
        let prev = link.load(fromByteOffset: 0, as: UnsafeMutableRawPointer?.self)
        let next = link.load(fromByteOffset: 8, as: UnsafeMutableRawPointer?.self)
        let size = link.load(fromByteOffset: 16, as: Int.self)
        let header = link.load(fromByteOffset: 24, as: Int.self)
        if let prev { prev.storeBytes(of: next, toByteOffset: 8, as: UnsafeMutableRawPointer?.self) } else { pointee.head = next }
        next?.storeBytes(of: prev, toByteOffset: 0, as: UnsafeMutableRawPointer?.self)
        pointee.liveBytes -= size
        pointee.liveCount -= 1
        free(ptr - header)
    }

    /// `roc_realloc` on a worker thread: a new allocation, the old contents
    /// copied, the old one freed.
    func reallocate(_ ptr: UnsafeMutableRawPointer?, _ size: Int, _ alignment: Int) -> UnsafeMutableRawPointer {
        guard let ptr else { return allocate(size, alignment) }
        let old = (ptr - linkBytes).load(fromByteOffset: 16, as: Int.self)
        let next = allocate(size, alignment)
        memcpy(next, ptr, min(old, size))
        deallocate(ptr)
        return next
    }

    /// Free every allocation the instance holds: its heap is abandoned with
    /// whatever Roc was doing in it.
    func discardHeap() {
        var cursor = pointee.head
        while let link = cursor {
            cursor = link.load(fromByteOffset: 8, as: UnsafeMutableRawPointer?.self)
            let header = link.load(fromByteOffset: 24, as: Int.self)
            free(link + linkBytes - header)
        }
        pointee.head = nil
        pointee.liveBytes = 0
        pointee.liveCount = 0
    }

    /// A stopped job unwinds at its next allocation or hosted call.
    func checkStop() {
        if pointee.inCall, pointee.stop.pointee != 0 {
            pointee.fault = 0
            pointee.messageLength = 0
            roc_guard_unwind(pointee.jump)
        }
    }

    /// Unwind the running call with a fault: the class (or, for a Roc crash,
    /// the class its message names) and the diagnostic, copied into the
    /// context without allocating.
    func fault(_ kind: WorkFault?, _ bytes: UnsafePointer<UInt8>?, _ len: Int) -> Never {
        let kept = min(max(len, 0), messageCapacity)
        if let bytes, kept > 0 { memcpy(pointee.message, bytes, kept) }
        pointee.messageLength = kept
        pointee.fault = (kind ?? classify(pointee.message, kept)).rawValue
        roc_guard_unwind(pointee.jump)
    }

    func fault(_ kind: WorkFault, _ message: StaticString) -> Never {
        fault(kind, message.utf8Start, message.utf8CodeUnitCount)
    }

    /// The class a crash message names (design.md, "Error Containment"):
    /// `contract:` and `resource_limit:` crashes are those classes; any other
    /// crash is `app_crash`.
    private func classify(_ text: UnsafeMutablePointer<UInt8>, _ len: Int) -> WorkFault {
        func starts(_ prefix: StaticString) -> Bool {
            let n = prefix.utf8CodeUnitCount
            return len >= n && memcmp(text, prefix.utf8Start, n) == 0
        }
        if starts("contract:") { return .contract }
        if starts("resource_limit:") { return .resourceLimit }
        return .appCrash
    }

    var faultMessage: String { String(decoding: UnsafeBufferPointer(start: pointee.message, count: pointee.messageLength), as: UTF8.self) }
}

// MARK: - Temporary files: what a builder writes

/// A file a job's builder wrote, in the temporary directory. Every
/// `FileEntry` naming it holds this, in whichever instance's table or
/// request it is; the file is removed when the last one goes, and every
/// one left is removed at quit.
final class TempFile {
    let path: String

    private static let lock: UnsafeMutablePointer<os_unfair_lock> = {
        let lock = UnsafeMutablePointer<os_unfair_lock>.allocate(capacity: 1)
        lock.initialize(to: os_unfair_lock())
        return lock
    }()
    private static var serial = 0
    private static var live: Set<String> = []

    /// A new, empty temporary file and a stream writing it, or nil.
    static func create() -> (TempFile, UnsafeMutableRawPointer)? {
        os_unfair_lock_lock(lock)
        serial += 1
        let n = serial
        os_unfair_lock_unlock(lock)
        let dir = getenv("TMPDIR").map { String(cString: $0) } ?? "/tmp/"
        let path = (dir.hasSuffix("/") ? dir : dir + "/") + "roc-native-macos-\(Int(ProcessInfo.processInfo.processIdentifier))-\(n)"
        // "x": exclusive creation (ISO C 7.21.5.3), so another file is never
        // overwritten.
        guard let stream = fopen(path, "wbx") else { return nil }
        os_unfair_lock_lock(lock)
        live.insert(path)
        os_unfair_lock_unlock(lock)
        return (TempFile(path), UnsafeMutableRawPointer(stream))
    }

    private init(_ path: String) { self.path = path }

    deinit {
        unlink(path)
        os_unfair_lock_lock(TempFile.lock)
        TempFile.live.remove(path)
        os_unfair_lock_unlock(TempFile.lock)
    }

    /// At quit: remove every temporary file still held.
    static func removeAll() {
        os_unfair_lock_lock(lock)
        let paths = live
        live.removeAll()
        os_unfair_lock_unlock(lock)
        for path in paths { unlink(path) }
    }
}

/// A file a job is writing (`Files.build!`): a temporary file open for
/// writing, until `finish!` makes it a file or the call that opened it
/// returns.
final class Builder {
    let temp: TempFile
    /// The `FILE` stream writing it, held untyped.
    private var stream: UnsafeMutableRawPointer?
    let name: String
    let mime: String
    private(set) var size: UInt64 = 0
    /// The call that opened it has returned (status 3).
    private(set) var expired = false

    init(temp: TempFile, stream: UnsafeMutableRawPointer, name: String, mime: String) {
        self.temp = temp
        self.stream = stream
        self.name = name
        self.mime = mime
    }

    deinit { close() }

    var isOpen: Bool { stream != nil && !expired }

    func write(_ bytes: UnsafeRawBufferPointer) -> Bool {
        guard let stream, bytes.count > 0 else { return true }
        guard fwrite(bytes.baseAddress, 1, bytes.count, stream.assumingMemoryBound(to: FILE.self)) == bytes.count else { return false }
        size += UInt64(bytes.count)
        return true
    }

    /// Copy a range of another file in. A built file is one temporary file,
    /// so appending a file copies its bytes; as the API specifies, they do
    /// not count against the job's output bound.
    func append(_ entry: FileEntry, _ start: UInt64, _ len: UInt64) -> Bool {
        var ok = true
        let progress = Files.chunks(entry, start, len, nil) { if ok { ok = write($0) } }
        return progress == .done && ok
    }

    /// Finish: the bytes are flushed and the stream closed. False when they
    /// could not be written.
    func finish() -> Bool {
        guard let stream else { return false }
        self.stream = nil
        return fclose(stream.assumingMemoryBound(to: FILE.self)) == 0
    }

    /// The call that opened it returned: nothing more is written, and its
    /// file goes when the builder does.
    func expire() {
        expired = true
        close()
    }

    private func close() {
        if let stream { fclose(stream.assumingMemoryBound(to: FILE.self)) }
        stream = nil
    }
}

/// What a worker instance's handle names.
enum Held {
    /// Minted by `mint!`, not yet a builder or a file.
    case empty
    case file(FileEntry)
    case builder(Builder)
    /// A builder `finish!` turned into a file (behind another handle).
    case finished
}

// MARK: - Jobs as they cross threads

enum WorkMode {
    case work, prepare, ask

    var name: String {
        switch self {
        case .work: return "work"
        case .prepare: return "prepare"
        case .ask: return "ask"
        }
    }
}

/// One job, as the main thread hands it to a worker thread: plain Swift
/// data. `payload` is `name:str input:rest`; for `prepare`, `prepare` is
/// `prep:str init:rest` and `prepareFiles` the preparation's files.
struct JobOrder {
    let id: UInt32
    let task: String
    let mode: WorkMode
    let payload: [UInt8]
    let files: [FileEntry]
    let prepare: [UInt8]
    let prepareFiles: [FileEntry]
    let maxOutput: UInt64
}

/// How a job ended, as the worker thread hands it back: plain Swift data.
enum JobOutcome {
    /// The answer's bytes (the task's `Wire` payload and its flag byte), the
    /// files it holds, and whether the instance holds a prepared state.
    case done(output: [UInt8], files: [FileEntry], held: Bool)
    /// The instance unwound: a `WorkFault` code, or 0 when the job was
    /// stopped, and the diagnostic. The instance has been replaced.
    case lost(UInt8, String)
}

enum WorkerMessage {
    case run(JobOrder)
    case forget
    case exit
}

enum WorkerReply {
    case answered(UInt32, JobOutcome)
    case forgot
}

// MARK: - A worker thread and its instance

/// One worker thread. The main thread posts it messages and may set its
/// stop flag; everything else here belongs to the worker thread.
final class WorkerThread {
    let seq: Int
    private let mailbox = NSCondition()
    private var inbox: [WorkerMessage] = []
    /// Written by the main thread (`stop()`), read by the worker.
    let stopFlag: UnsafeMutablePointer<UInt8>
    private let reply: (WorkerThread, WorkerReply) -> Void

    // The worker thread's own state.
    private var context: UnsafeMutablePointer<WorkerContext>!
    private(set) var table = HandleTable()
    private var held: RocBox? = nil
    private var opened: [UInt64] = []
    private var outputLeft: UInt64 = 0

    /// The stack a worker thread runs Roc on: jobs recurse (the payload
    /// codec does, up to 128 levels of the app's data), and a secondary
    /// thread's default stack is 512 KiB. Reserved, not committed.
    static let stackBytes = 64 << 20

    init(seq: Int, reply: @escaping (WorkerThread, WorkerReply) -> Void) {
        self.seq = seq
        self.reply = reply
        stopFlag = .allocate(capacity: 1)
        stopFlag.initialize(to: 0)
        let thread = Thread { [self] in self.main() }
        thread.name = "roc worker \(seq)"
        thread.stackSize = WorkerThread.stackBytes
        thread.start()
    }

    deinit { stopFlag.deallocate() }

    /// On the main thread: post a message.
    func send(_ message: WorkerMessage) {
        mailbox.lock()
        inbox.append(message)
        mailbox.signal()
        mailbox.unlock()
    }

    /// On the main thread: stop this worker. A running job unwinds at its
    /// next allocation or hosted call; the thread then discards its instance
    /// and ends. Nothing it answers afterwards is delivered.
    func stop() {
        stopFlag.pointee = 1
        send(.exit)
    }

    private func take() -> WorkerMessage {
        mailbox.lock()
        while inbox.isEmpty { mailbox.wait() }
        let message = inbox.removeFirst()
        mailbox.unlock()
        return message
    }

    private func main() {
        let jump = UnsafeMutablePointer<jmp_buf>.allocate(capacity: 1)
        let message = UnsafeMutablePointer<UInt8>.allocate(capacity: messageCapacity)
        context = .allocate(capacity: 1)
        context.initialize(to: WorkerContext(jump: jump, stop: stopFlag, message: message, tableStart: table.slots, tableBytes: table.slotBytes, worker: Unmanaged.passUnretained(self).toOpaque()))
        pthread_setspecific(workerKey, context)
        loop: while stopFlag.pointee == 0 {
            switch take() {
            case .exit: break loop
            case .forget:
                forget()
                reply(self, .forgot)
            case .run(let order):
                let outcome = run(order)
                if stopFlag.pointee == 0 { reply(self, .answered(order.id, outcome)) }
            }
        }
        if Host.tracing { fputs("worker \(seq): ended; instance discarded (\(context.pointee.liveCount) allocations freed)\n", __stderrp) }
        discard()
        pthread_setspecific(workerKey, nil)
        context.deinitialize(count: 1)
        context.deallocate()
        jump.deallocate()
        message.deallocate()
    }

    // MARK: Calls into the instance

    /// Run a job; a fault replaces the instance.
    private func run(_ order: JobOrder) -> JobOutcome {
        outputLeft = order.maxOutput
        if order.mode == .prepare {
            if let state = held {
                held = nil
                context.pointee.inCall = true
                let forgot = Roc.forgetForHostGuarded(context.pointee.jump, state)
                context.pointee.inCall = false
                if !forgot { return lost() }
                drain()
            }
            guard let handles = mint(order.prepareFiles) else { return resourceLost(order.prepareFiles.count) }
            let payload = RocList.ownedBytes(order.prepare)
            let list = RocList.ownedBoxesU64(handles)
            context.pointee.inCall = true
            let prepared = Roc.prepareForHostGuarded(context.pointee.jump, payload, list)
            context.pointee.inCall = false
            closeOpened()
            guard let state = prepared else { return lost() }
            held = state
            drain()
        }
        if order.mode != .work, held == nil { fatal("a job of a preparation's task reached a worker that holds no state") }
        guard let handles = mint(order.files) else { return resourceLost(order.files.count) }
        let payload = RocList.ownedBytes(order.payload)
        let list = RocList.ownedBoxesU64(handles)
        var answer: RocList? = nil
        context.pointee.inCall = true
        if order.mode == .work {
            answer = Roc.workForHostGuarded(context.pointee.jump, payload, list)
        } else {
            let state = held
            held = nil
            if let step = Roc.askForHostGuarded(context.pointee.jump, state, payload, list) {
                held = step.held
                answer = step.out
            }
        }
        context.pointee.inCall = false
        closeOpened()
        guard let answer else { return lost() }
        let bytes = answer.bytes
        answer.releaseBytes()
        // `n:u32 (token:u64)*n output:rest`: the instance's tokens of the
        // files the answer holds, read before the call's releases are drained.
        var r = Reader(bytes)
        guard bytes.count >= 4 else { return contractLost("contract: a job's entry returned an answer without its file count") }
        let n = Int(r.u32())
        guard bytes.count >= 4 + 8 * n else { return contractLost("contract: a job's entry returned a truncated answer") }
        var files: [FileEntry] = []
        for _ in 0..<n {
            guard case .file(let entry) = table.held(r.u64()) else {
                return contractLost("contract: a job's answer names a handle that is not a finished file")
            }
            files.append(entry)
        }
        let output = Array(bytes[(4 + 8 * n)...])
        drain()
        return .done(output: output, files: files, held: held != nil)
    }

    /// Let go of the prepared state (an eviction).
    private func forget() {
        guard let state = held else { return }
        held = nil
        context.pointee.inCall = true
        let forgot = Roc.forgetForHostGuarded(context.pointee.jump, state)
        context.pointee.inCall = false
        if !forgot { _ = lost() } else { drain() }
    }

    /// The call unwound: report why, and replace the instance.
    private func lost() -> JobOutcome {
        let outcome = JobOutcome.lost(context.pointee.fault, context.faultMessage)
        if Host.tracing {
            let why = context.pointee.fault == 0 ? "stopped" : WorkFault.of(context.pointee.fault).name
            fputs("worker \(seq): call unwound (\(why)); instance discarded, \(context.pointee.liveCount) allocations (\(context.pointee.liveBytes) bytes) freed\n", __stderrp)
        }
        discard()
        return outcome
    }

    private func contractLost(_ message: String) -> JobOutcome {
        discard()
        return .lost(WorkFault.contract.rawValue, message)
    }

    private func resourceLost(_ count: Int) -> JobOutcome {
        discard()
        return .lost(WorkFault.resourceLimit.rawValue, "resource_limit: a job was sent \(count) files and its instance has room for fewer")
    }

    /// Discard the instance: free its whole heap (whatever Roc was doing in
    /// it), its prepared state with it, then its handle table, whose files
    /// and builders go with it. The next call starts a fresh instance.
    private func discard() {
        context.discardHeap()
        held = nil
        opened = []
        table = HandleTable()
        context.pointee.tableStart = table.slots
        context.pointee.tableBytes = table.slotBytes
        context.pointee.fault = 0
        context.pointee.messageLength = 0
    }

    /// A handle for each file a call is given, in order; nil when the table
    /// has no room for all of them.
    private func mint(_ files: [FileEntry]) -> [UnsafeMutableRawPointer]? {
        var boxes: [UnsafeMutableRawPointer] = []
        for file in files {
            guard let box = table.mint(.file(file)) else { return nil }
            boxes.append(box)
        }
        return boxes
    }

    /// Close every builder the call that just returned opened: a builder
    /// never outlives its call, so one a prepared state kept is refused
    /// (status 3) to every later job.
    private func closeOpened() {
        for token in opened {
            if case .builder(let b) = table.held(token), b.isOpen { b.expire() }
        }
        opened = []
    }

    /// Drop what Roc released during the call.
    private func drain() { _ = table.drainReleased() }

    // MARK: Hosted effects, on this thread inside a call

    /// The status a builder effect answers for `token`: nil when it is an
    /// open builder, 2 when it is not one, 3 when its call has returned.
    private func refusal(_ token: UInt64) -> UInt8? {
        guard case .builder(let b) = table.held(token) else { return 2 }
        if b.expired { return 3 }
        return b.isOpen ? nil : 2
    }

    func read(_ token: UInt64, _ start: UInt64, _ len: UInt64) -> [UInt8]? {
        guard case .file(let entry) = table.held(token), start <= entry.size, len <= entry.size - start else { return nil }
        var bytes: [UInt8] = []
        bytes.reserveCapacity(Int(len))
        return Files.chunks(entry, start, len, nil, { bytes.append(contentsOf: $0) }) == .done ? bytes : nil
    }

    func size(_ token: UInt64) -> UInt64 {
        if case .file(let entry) = table.held(token) { return entry.size }
        return 0
    }

    func mintEmpty() -> UnsafeMutableRawPointer? { table.mint(.empty) }

    /// Nil when no temporary file could be made.
    func open(_ token: UInt64, _ name: String, _ mime: String, _ from: UInt64, _ start: UInt64, _ len: UInt64) -> UInt8? {
        guard case .empty = table.held(token) else { return 2 }
        guard let (temp, stream) = TempFile.create() else { return nil }
        let builder = Builder(temp: temp, stream: stream, name: name, mime: mime)
        if from != 0 {
            guard case .file(let source) = table.held(from), start <= source.size, len <= source.size - start else { return 2 }
            if !builder.append(source, start, len) { return nil }
        }
        table.update(token, .builder(builder))
        opened.append(token)
        return 0
    }

    /// Nil when the bytes could not be written.
    func append(_ token: UInt64, _ bytes: UnsafeRawBufferPointer) -> UInt8? {
        if let status = refusal(token) { return status }
        guard case .builder(let b) = table.held(token) else { return 2 }
        if UInt64(bytes.count) > outputLeft { return 1 }
        outputLeft -= UInt64(bytes.count)
        return b.write(bytes) ? 0 : nil
    }

    func appendFile(_ token: UInt64, _ file: UInt64, _ start: UInt64, _ len: UInt64) -> UInt8? {
        if let status = refusal(token) { return status }
        guard case .builder(let b) = table.held(token),
              case .file(let source) = table.held(file), start <= source.size, len <= source.size - start
        else { return 2 }
        return b.append(source, start, len) ? 0 : nil
    }

    func finish(_ token: UInt64, _ file: UInt64) -> UInt8? {
        if let status = refusal(token) { return status }
        guard case .builder(let b) = table.held(token), case .empty = table.held(file) else { return 2 }
        guard b.finish() else { return nil }
        table.update(file, .file(FileEntry(path: b.temp.path, size: b.size, name: b.name, mime: b.mime, backing: b.temp)))
        table.update(token, .finished)
        return 0
    }
}

// MARK: - The hosted functions (Hosted.roc), served on a worker thread

/// The platform's hosted functions, which glue/SwiftGlue.roc exports as the
/// `roc_task_*` symbols. Each runs on the worker thread inside a job's call;
/// anywhere else it is a contract error. A hosted function owns its list
/// arguments and releases them. When one must unwind the call (a stop, a
/// resource limit, a file the host cannot write), it decides with no Swift
/// object still live in its frame, since unwinding skips the frame.
enum RocHosted: RocHostedFunctions {
    static func hostedRead(_ token: UInt64, _ start: UInt64, _ len: UInt64) -> RocList {
        let context = WorkerContext.job("File.read!")
        guard let bytes = context.pointee.thread.read(token, start, len) else { return .empty }
        return .ownedBytes(bytes)
    }

    static func hostedSize(_ token: UInt64) -> UInt64 {
        let context = WorkerContext.job("Builder.finish!")
        return context.pointee.thread.size(token)
    }

    static func hostedMint() -> UnsafeMutableRawPointer {
        let context = WorkerContext.job("Files.build!")
        if let box = context.pointee.thread.mintEmpty() { return box }
        context.fault(.resourceLimit, "resource_limit: a worker job holds more than 64 files and builders at once")
    }

    static func hostedOpen(_ token: UInt64, _ name: RocList, _ mime: RocList, _ from: UInt64, _ start: UInt64, _ len: UInt64) -> UInt8 {
        let context = WorkerContext.job("Files.build!")
        let status = context.pointee.thread.open(token, String(decoding: name.bytes, as: UTF8.self), String(decoding: mime.bytes, as: UTF8.self), from, start, len)
        name.releaseBytes()
        mime.releaseBytes()
        if let status { return status }
        context.fault(.executor, "executor: the host could not create a temporary file for a builder")
    }

    static func hostedAppend(_ token: UInt64, _ bytes: RocList) -> UInt8 {
        let context = WorkerContext.job("Builder.append!")
        let status = context.pointee.thread.append(token, UnsafeRawBufferPointer(start: bytes.elements, count: bytes.length))
        bytes.releaseBytes()
        if let status { return status }
        context.fault(.executor, "executor: the host could not write a builder's temporary file")
    }

    static func hostedAppendFile(_ token: UInt64, _ file: UInt64, _ start: UInt64, _ len: UInt64) -> UInt8 {
        let context = WorkerContext.job("Builder.append_file!")
        if let status = context.pointee.thread.appendFile(token, file, start, len) { return status }
        context.fault(.executor, "executor: the host could not copy a file into a builder")
    }

    static func hostedFinish(_ token: UInt64, _ file: UInt64) -> UInt8 {
        let context = WorkerContext.job("Builder.finish!")
        if let status = context.pointee.thread.finish(token, file) { return status }
        context.fault(.executor, "executor: the host could not write a builder's temporary file")
    }
}

// MARK: - The pool, on the main thread

/// The state of a preparation a worker may hold: the preparation's name, its
/// input's bytes and the page's handles and ranges of its files. A job over
/// an equal key may run on the worker that holds it.
struct PrepKey: Equatable {
    let name: String
    let initBytes: [UInt8]
    /// `token, start, len` for each of the preparation's files.
    let ranges: [UInt64]

    func names(_ token: UInt64) -> Bool { stride(from: 0, to: ranges.count, by: 3).contains { ranges[$0] == token } }
}

/// One job in flight, on the main thread.
final class WorkJob {
    let id: UInt32
    let task: String
    let payload: [UInt8]
    let files: [FileEntry]
    let prepared: (key: PrepKey, prepare: [UInt8], files: [FileEntry])?
    /// `on_cancel: Finish`: a cancelled running job completes and its answer
    /// is dropped.
    let finish: Bool
    /// When a finishing job is stopped anyway: its timeout, or ten minutes
    /// after it was performed.
    let endBy: Double
    let performed = Date().timeIntervalSince1970
    var slot: WorkerSlot?
    var timer: Timer?
    var finishing = false

    init(id: UInt32, task: String, payload: [UInt8], files: [FileEntry], prepared: (key: PrepKey, prepare: [UInt8], files: [FileEntry])?, finish: Bool, timeoutMs: UInt32) {
        self.id = id
        self.task = task
        self.payload = payload
        self.files = files
        self.prepared = prepared
        self.finish = finish
        endBy = Date().timeIntervalSince1970 + Double(timeoutMs > 0 ? timeoutMs : WorkPool.maxTimeoutMs) / 1000
    }
}

/// A worker thread as the pool sees it.
final class WorkerSlot {
    let worker: WorkerThread
    var job: WorkJob?
    /// The prepared state the worker holds, as far as the pool knows.
    var key: PrepKey?
    var used = 0
    /// Forgets posted and not yet answered: the worker takes no job until
    /// they are.
    var forgetting = 0

    init(_ worker: WorkerThread) { self.worker = worker }
}

/// The worker pool: its slots, the jobs waiting for one and every job in
/// flight by id. Main thread only.
final class WorkPool {
    /// The longest a request may run (design.md: ten minutes).
    static let maxTimeoutMs: UInt32 = 600_000

    /// The most bytes one job may append to its builders (`maxOutputBytes`,
    /// 256 MiB by default; `ROC_MAX_OUTPUT_BYTES` lowers it).
    static let maxOutputBytes: UInt64 = ProcessInfo.processInfo.environment["ROC_MAX_OUTPUT_BYTES"].flatMap { UInt64($0) } ?? 256 << 20

    /// How many worker threads run jobs at once: one per core but the
    /// main thread's (the UI keeps a core), at least one and at most eight
    /// (roc-signals' default `maxWorkers`). `ROC_WORKERS` sets it, as does
    /// a spec's `(worker-pool N)` before the first job.
    var limit: Int = {
        if let given = ProcessInfo.processInfo.environment["ROC_WORKERS"].flatMap({ Int($0) }), given >= 1 { return min(given, 64) }
        return max(1, min(8, ProcessInfo.processInfo.activeProcessorCount - 1))
    }()

    var slots: [WorkerSlot] = []
    var queue: [WorkJob] = []
    var jobs: [UInt32: WorkJob] = [:]
    var clock = 0
    var closed = false
    var pumpQueued = false
    var serial = 0

    /// For a spec's `expect-workers` and ROC_TRACE.
    var spawned = 0, answered = 0, stopped = 0, lost = 0, dropped = 0, timedOut = 0

    var summary: String {
        let running = slots.filter { $0.job != nil }.count
        return "workers: limit \(limit), \(slots.count) live, \(running) running, \(queue.count) queued; \(spawned) started, \(answered) answered, \(lost) lost, \(stopped) stopped, \(timedOut) timed out, \(dropped) dropped"
    }

    func holder(_ key: PrepKey) -> WorkerSlot? { slots.first { $0.key == key } }
}

extension Host {
    static let tracing = ProcessInfo.processInfo.environment["ROC_TRACE"] != nil

    // MARK: FX 8

    /// `FX` kind 8, Work: `task:str input:u32+bytes n:u32 (token:u64 start:u64
    /// len:u64)*n timeout_ms:u32 cancel:u8 prepared:u8 [prep:str input_len:u32
    /// input_files:u32]`. The files are resolved now, while the handles the
    /// batch released still name them, and cross whole, as `FileEntry`s.
    func startWork(id: UInt32, _ r: inout Reader) {
        let task = r.str()
        let input = r.raw(Int(r.u32()))
        let count = Int(r.u32())
        var files: [FileEntry] = []
        var ranges: [UInt64] = []
        for _ in 0..<count {
            let token = r.u64(), start = r.u64(), len = r.u64()
            files.append(resolve(token))
            ranges += [token, start, len]
        }
        let timeout = min(r.u32(), WorkPool.maxTimeoutMs), cancel = r.u8(), flag = r.u8()
        guard cancel == 1 || cancel == 2 else { fatal("contract: work request cancel policy \(cancel) is not 1 or 2") }
        let job: WorkJob
        switch flag {
        case 0:
            job = WorkJob(id: id, task: task, payload: encodeStr(task) + input, files: files, prepared: nil, finish: cancel == 2, timeoutMs: timeout)
        case 1:
            let prep = r.str()
            let initLen = Int(r.u32()), initFiles = Int(r.u32())
            guard initLen <= input.count, initFiles <= count else { fatal("contract: malformed preparation operands for worker task \(task)") }
            let initBytes = Array(input[..<initLen])
            let key = PrepKey(name: prep, initBytes: initBytes, ranges: Array(ranges[..<(3 * initFiles)]))
            job = WorkJob(id: id, task: task, payload: encodeStr(task) + input[initLen...], files: Array(files[initFiles...]),
                          prepared: (key, encodeStr(prep) + initBytes, Array(files[..<initFiles])), finish: cancel == 2, timeoutMs: timeout)
        default:
            fatal("contract: work request flag \(flag) is not 0 or 1")
        }
        work.jobs[id] = job
        if timeout > 0 {
            let timer = Timer(timeInterval: Double(timeout) / 1000, repeats: false) { [weak self] _ in self?.timedOut(job) }
            RunLoop.main.add(timer, forMode: .common)
            job.timer = timer
        }
        work.queue.append(job)
        trace("work \(id) \(task): queued (\(job.files.count) files\(job.prepared.map { ", preparation \($0.key.name)" } ?? ""))")
        // After the batch: a CANCEL later in it still wins over a free worker.
        pumpSoon()
    }

    private func encodeStr(_ s: String) -> [UInt8] {
        var b = Bytes()
        b.str(s)
        return b.bytes
    }

    // MARK: Placement

    func pumpSoon() {
        guard !work.pumpQueued else { return }
        work.pumpQueued = true
        DispatchQueue.main.async {
            self.work.pumpQueued = false
            self.pumpWork()
        }
    }

    /// Hand waiting jobs to workers: first each job whose state an idle
    /// worker holds, there; then the rest in order, each on an idle worker
    /// holding nothing, a new worker while the pool has room, or the idle
    /// holder used least recently, whose state it replaces. A job whose
    /// state a busy worker holds waits for it.
    func pumpWork() {
        guard !work.closed, !halted else { return }
        var i = 0
        while i < work.queue.count {
            let job = work.queue[i]
            if let key = job.prepared?.key, let holder = work.holder(key), holder.job == nil, holder.forgetting == 0 {
                work.queue.remove(at: i)
                post(job, to: holder, .ask)
            } else {
                i += 1
            }
        }
        i = 0
        while i < work.queue.count {
            let job = work.queue[i]
            if let key = job.prepared?.key, work.holder(key) != nil { i += 1; continue }
            guard let slot = freeSlot() else { return }
            work.queue.remove(at: i)
            post(job, to: slot, job.prepared == nil ? .work : .prepare)
        }
    }

    private func freeSlot() -> WorkerSlot? {
        var lru: WorkerSlot? = nil
        var forgetting = false
        for slot in work.slots where slot.job == nil {
            if slot.forgetting > 0 { forgetting = true; continue }
            if slot.key == nil { return slot }
            if lru == nil || slot.used < lru!.used { lru = slot }
        }
        if forgetting { return nil }
        if work.slots.count < work.limit { return spawnWorker() }
        return lru
    }

    private func spawnWorker() -> WorkerSlot {
        work.serial += 1
        work.spawned += 1
        let worker = WorkerThread(seq: work.serial) { [weak self] worker, reply in
            DispatchQueue.main.async { self?.workerReplied(worker, reply) }
        }
        let slot = WorkerSlot(worker)
        work.slots.append(slot)
        trace("worker \(worker.seq): started (\(work.slots.count) of \(work.limit))")
        return slot
    }

    private func post(_ job: WorkJob, to slot: WorkerSlot, _ mode: WorkMode) {
        slot.job = job
        job.slot = slot
        work.clock += 1
        slot.used = work.clock
        if mode == .prepare { slot.key = job.prepared!.key }
        let order = JobOrder(id: job.id, task: job.task, mode: mode, payload: job.payload, files: job.files,
                             prepare: job.prepared?.prepare ?? [], prepareFiles: job.prepared?.files ?? [], maxOutput: WorkPool.maxOutputBytes)
        trace("work \(job.id) \(job.task): \(mode.name) on worker \(slot.worker.seq)")
        slot.worker.send(.run(order))
    }

    // MARK: Answers

    /// A worker's reply, on the main thread. Only a reply from a worker
    /// still in the pool, for the job it was given, counts; a job's answer
    /// enters Roc only while its id is still tracked by the same job.
    func workerReplied(_ worker: WorkerThread, _ reply: WorkerReply) {
        guard !work.closed, let slot = work.slots.first(where: { $0.worker === worker }) else {
            trace("worker \(worker.seq): reply after it was stopped: dropped")
            return
        }
        switch reply {
        case .forgot:
            slot.forgetting -= 1
            pumpWork()
        case .answered(let id, let outcome):
            guard let job = slot.job, job.id == id else { return }
            slot.job = nil
            job.slot = nil
            job.timer?.invalidate()
            job.timer = nil
            let current = !job.finishing && work.jobs[id] === job
            if current { work.jobs.removeValue(forKey: id) }
            let ms = Int((Date().timeIntervalSince1970 - job.performed) * 1000)
            switch outcome {
            case .done(let output, let files, let held):
                if !held { slot.key = nil }
                if current {
                    work.answered += 1
                    trace("work \(id) \(job.task): answered in \(ms) ms (\(output.count) bytes, \(files.count) files)")
                    deliverWork(id, output, files)
                } else {
                    work.dropped += 1
                    trace("work \(id) \(job.task): finished after it was cancelled; answer dropped")
                }
            case .lost(let code, let message):
                // The worker discarded its instance and holds a fresh one.
                slot.key = nil
                work.lost += 1
                let fault = WorkFault.of(code)
                if current {
                    say("roc worker fault [\(fault.name)] in task \"\(job.task)\": \(message)")
                    send(EngineInstance.effectNode, id, [11, fault.rawValue])
                } else {
                    work.dropped += 1
                    trace("work \(id) \(job.task): lost [\(fault.name)] after it was cancelled; dropped")
                }
            }
            // A state keyed on a file the page no longer holds is let go.
            if let key = slot.key, key.ranges.enumerated().contains(where: { $0.offset % 3 == 0 && fileHandles.entry($0.element) == nil }) {
                evict(slot)
            }
            pumpWork()
        }
    }

    /// Deliver a job's answer as result tag 10: through `roc_engine_files`
    /// with the page's new handles for its files, or as a plain result when
    /// it holds none. With no room for its files the job is lost to a
    /// resource limit and nothing is minted.
    func deliverWork(_ id: UInt32, _ output: [UInt8], _ files: [FileEntry]) {
        var head = Bytes()
        head.bytes = [10]
        head.u32(UInt32(files.count))
        if files.isEmpty { return send(EngineInstance.effectNode, id, head.bytes + output) }
        if applying {
            DispatchQueue.main.async { self.deliverWork(id, output, files) }
            return
        }
        if halted || engine.dropped { return }
        guard fileHandles.free >= files.count else {
            say("roc worker fault [resource_limit] in work \(id): the job answered with \(files.count) files and the page has room for \(fileHandles.free)")
            return send(EngineInstance.effectNode, id, [11, WorkFault.resourceLimit.rawValue])
        }
        var boxes: [UnsafeMutableRawPointer] = []
        for file in files {
            boxes.append(fileHandles.mint(file)!)
            head.u64(file.size); head.str(file.name); head.str(file.mime)
        }
        apply(engine.files(node: EngineInstance.effectNode, handler: id, record: head.bytes + output, handles: boxes))
    }

    // MARK: Cancellation, timeouts, teardown

    /// `CANCEL` of a job: a waiting job is dropped; a running one is stopped
    /// (its worker discarded and replaced), or with `on_cancel: Finish` runs
    /// on until its end bound and its answer is dropped. Returns whether `id`
    /// was a job.
    func cancelWork(_ id: UInt32) -> Bool {
        guard let job = work.jobs.removeValue(forKey: id) else { return false }
        job.timer?.invalidate()
        job.timer = nil
        if let index = work.queue.firstIndex(where: { $0 === job }) {
            work.queue.remove(at: index)
            trace("work \(id) \(job.task): cancelled while waiting")
        } else if let slot = job.slot {
            if job.finish {
                job.finishing = true
                let timer = Timer(timeInterval: max(0, job.endBy - Date().timeIntervalSince1970), repeats: false) { [weak self] _ in self?.overran(job) }
                RunLoop.main.add(timer, forMode: .common)
                job.timer = timer
                trace("work \(id) \(job.task): cancelled; finishing on worker \(slot.worker.seq)")
            } else {
                stopWorker(slot, "cancelled")
            }
        }
        pumpSoon()
        return true
    }

    /// A job's timeout: it is stopped wherever it is (a finishing one too)
    /// and answered `Timeout`.
    private func timedOut(_ job: WorkJob) {
        job.timer = nil
        guard work.jobs[job.id] === job else { return }
        work.jobs.removeValue(forKey: job.id)
        work.timedOut += 1
        if let index = work.queue.firstIndex(where: { $0 === job }) { work.queue.remove(at: index) }
        if let slot = job.slot { stopWorker(slot, "timed out") }
        trace("work \(job.id) \(job.task): timed out")
        send(EngineInstance.effectNode, job.id, [7])
        pumpWork()
    }

    /// A finishing job reached its end bound: its worker is stopped.
    private func overran(_ job: WorkJob) {
        job.timer = nil
        guard job.finishing, let slot = job.slot, !work.closed else { return }
        stopWorker(slot, "finishing job overran")
        pumpWork()
    }

    /// Stop a worker and take it out of the pool. Its thread unwinds the job
    /// at its next allocation or hosted call, discards the instance and
    /// ends; a new worker takes its place when a job needs one.
    private func stopWorker(_ slot: WorkerSlot, _ why: String) {
        work.slots.removeAll { $0 === slot }
        if let job = slot.job { job.slot = nil }
        slot.job = nil
        slot.worker.stop()
        work.stopped += 1
        trace("worker \(slot.worker.seq): stopped (\(why))")
    }

    /// Let go of an idle worker's prepared state.
    private func evict(_ slot: WorkerSlot) {
        guard slot.key != nil else { return }
        slot.key = nil
        slot.forgetting += 1
        slot.worker.send(.forget)
        trace("worker \(slot.worker.seq): state released")
    }

    /// The page released these file tokens: no prepared state keyed on one
    /// outlives it (a busy holder lets go when its job answers).
    func releaseWorkStates(_ tokens: [UInt64]) {
        guard !tokens.isEmpty else { return }
        for slot in work.slots where slot.job == nil {
            if let key = slot.key, tokens.contains(where: key.names) { evict(slot) }
        }
    }

    /// Teardown: every worker is stopped and every waiting job dropped;
    /// nothing a worker answers afterwards is delivered. The temporary files
    /// builders wrote are removed.
    func teardownWorkers() {
        work.closed = true
        for job in work.jobs.values { job.timer?.invalidate() }
        work.jobs.removeAll()
        work.queue.removeAll()
        for slot in work.slots { slot.worker.stop() }
        if !work.slots.isEmpty { trace("workers: \(work.slots.count) stopped at teardown") }
        work.slots.removeAll()
        TempFile.removeAll()
    }
}
